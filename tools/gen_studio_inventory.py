#!/usr/bin/env python3
"""Regenerate portable Studio contracts from this checkout, or verify --check."""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from dgx_monarch.studio.inventory import build_inventory, discover_workflows  # noqa: E402
from dgx_monarch.studio.presentation import presentation_contract  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    _, workflows = discover_workflows(ROOT)
    documents = {"parity.json": build_inventory(ROOT), "presentation.json": presentation_contract(),
                 "workflows.json": {"schema_version": 1, "workflows": workflows}}
    stale = []
    for name, value in documents.items():
        target = ROOT / "src/dgx_monarch/studio/data" / name
        expected = json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected, encoding="utf-8")
    js = ("// Generated by tools/gen_studio_inventory.py; do not edit.\n"
          + "export const PRESENTATION = " + json.dumps(presentation_contract(), ensure_ascii=False, sort_keys=True) + ";\n"
          + "export const MEMORY = Object.fromEntries(Object.entries(PRESENTATION.memory).map(([key, value]) => [key, value.hex]));\n"
          + "export const STATUS = Object.fromEntries(Object.entries(PRESENTATION.status).map(([key, value]) => [key, value.hex]));\n"
          + "export function formatMetric(value, unit, sourceUnits = false) {\n"
          + "  if (typeof value !== 'number' || !Number.isFinite(value)) return 'unknown';\n"
          + "  const spec = PRESENTATION.units[unit];\n"
          + "  const number = value / (sourceUnits ? spec.divisor : 1);\n"
          + "  return number.toFixed(spec.precision) + (unit === 'count' ? '' : ' ' + unit);\n}\n"
          + "export function availableMemoryStatus(value) {\n"
          + "  if (typeof value !== 'number' || !Number.isFinite(value)) return 'unknown';\n"
          + "  const threshold = PRESENTATION.thresholds.available_memory_gib;\n"
          + "  return value > threshold.value ? threshold.above : threshold.otherwise;\n}\n")
    js_target = ROOT / "web/js/dgx_monarch_presentation.js"
    if args.check:
        if not js_target.exists() or js_target.read_text(encoding="utf-8") != js:
            stale.append(str(js_target.relative_to(ROOT)))
    else:
        js_target.write_text(js, encoding="utf-8")
    package = ROOT / "src/dgx_monarch"
    resources = sorted(path for directory in (package / "studio/data", package / "studio/static")
                       for path in directory.rglob("*") if path.is_file())
    hashes = {path.relative_to(package).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest() for path in resources}
    manifest = package / "studio/resource_hashes.py"
    expected_manifest = ('"""Generated Studio resource hashes; regenerate after building the frontend."""\n\n'
                         + "RESOURCE_SHA256 = " + repr(hashes) + "\n")
    if args.check:
        if not manifest.exists() or manifest.read_text(encoding="utf-8") != expected_manifest:
            stale.append(str(manifest.relative_to(ROOT)))
    else:
        manifest.write_text(expected_manifest, encoding="utf-8")
    if stale:
        print("Stale Studio contracts: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("Studio inventory verified" if args.check else "Studio inventory regenerated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
